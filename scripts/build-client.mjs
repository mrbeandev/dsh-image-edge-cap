import { mkdir, writeFile } from 'node:fs/promises';
import { createClientPlugin } from '../client/index.mjs';

// The installed DSH serves lazy factory registrations, not ESM modules. Keep
// require('react') inside materialization so it uses the GUI's React singleton.
const output = new URL('../lib/client.js', import.meta.url);
const bundle = `// Generated by scripts/build-client.mjs; edit client/index.mjs instead.
window.__ModuleLoader__.load({
  id: 'dsh-image-edge-cap',
  factory: (${createClientPlugin.toString()})
});
`;
await mkdir(new URL('../lib/', import.meta.url), { recursive: true });
await writeFile(output, bundle, 'utf8');
console.log(`Built ${output.pathname}`);
